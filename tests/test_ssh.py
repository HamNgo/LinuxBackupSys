"""Optional real SSH integration using an isolated localhost sshd.

Run with LINUX_BACKUP_TEST_SSH=1 as root on a disposable Ubuntu CI/VM.
No global SSH configuration, keys, accounts or services are changed.
"""
import json
import os
from pathlib import Path
import pwd
import shutil
import socket
import subprocess
import time
import unittest

from client.operations import Client
from common.core import BackupError
from common.manifest import scan, verify
from tests.support import Fixture

ENABLED = os.environ.get("LINUX_BACKUP_TEST_SSH") == "1"


@unittest.skipUnless(ENABLED, "Set LINUX_BACKUP_TEST_SSH=1 for disposable localhost sshd integration")
class SSHIntegrationTests(Fixture):
    def setUp(self):
        super().setUp()
        if os.geteuid() != 0 or not Path("/usr/sbin/sshd").exists():
            self.fail("Opt-in SSH test requires root and openssh-server in a disposable Ubuntu environment")
        if not Path("/run/sshd").is_dir():
            self.fail("Prepare /run/sshd in the disposable environment before running SSH tests")
        user = pwd.getpwuid(os.geteuid()).pw_name
        # Existing empty files are replaced ONLY inside this test-owned tempdir.
        Path(self.client_cfg["SSH_IDENTITY"]).unlink()
        host_key = self.base / "host-key"
        for key in (host_key, Path(self.client_cfg["SSH_IDENTITY"])):
            subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)], check=True)
        authorized = self.base / "authorized_keys"
        authorized.write_text(Path(self.client_cfg["SSH_IDENTITY"] + ".pub").read_text())
        authorized.chmod(0o600)
        with socket.socket() as sock:
            sock.bind(("127.0.0.1", 0))
            port = sock.getsockname()[1]
        sshd_cfg = self.base / "sshd_config"
        sshd_cfg.write_text(
            f'Port {port}\nListenAddress 127.0.0.1\nHostKey "{host_key}"\n'
            f'PidFile "{self.base / "sshd.pid"}"\nAuthorizedKeysFile "{authorized}"\n'
            f'AllowUsers {user}\nPermitRootLogin prohibit-password\nPasswordAuthentication no\n'
            'KbdInteractiveAuthentication no\nUsePAM yes\nStrictModes yes\nPermitUserRC no\n'
            'AllowTcpForwarding no\nX11Forwarding no\nLogLevel ERROR\n')
        subprocess.run(["/usr/sbin/sshd", "-t", "-f", str(sshd_cfg)], check=True)
        self.sshd_log = (self.base / "sshd.log").open("wb")
        self.addCleanup(self.sshd_log.close)
        self.sshd = subprocess.Popen(["/usr/sbin/sshd", "-D", "-e", "-f", str(sshd_cfg)],
                                     stdout=self.sshd_log, stderr=self.sshd_log)
        self.addCleanup(self.stop_sshd)
        deadline = time.monotonic() + 5
        while True:
            try:
                with socket.create_connection(("127.0.0.1", port), timeout=0.2):
                    break
            except OSError:
                if time.monotonic() > deadline:
                    self.fail("Isolated sshd did not start")
                time.sleep(0.05)
        public = host_key.with_suffix(".pub").read_text().split()
        # Trust the exact host key generated by this fixture, not ssh-keyscan.
        Path(self.client_cfg["SSH_KNOWN_HOSTS"]).write_text(f"[127.0.0.1]:{port} {public[0]} {public[1]}\n")
        self.client_cfg.update(SSH_HOST="127.0.0.1", SSH_USER=user, SSH_PORT=port)

    def stop_sshd(self):
        if self.sshd.poll() is None:
            self.sshd.terminate()
            try:
                self.sshd.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.sshd.kill()
                self.sshd.wait(timeout=5)

    def test_real_ssh_backup_restore_and_auth_host_failure(self):
        self.data()
        expected = scan(self.source)
        client = Client(self.client_cfg)
        snapshot = client.execute("backup")["snapshot_id"]
        result = client.execute("restore", snapshot_id=snapshot, path=".")
        verify(Path(result["destination"]), expected)
        with self.subTest("unknown host key"):
            known_hosts = Path(self.client_cfg["SSH_KNOWN_HOSTS"])
            saved = known_hosts.read_text()
            known_hosts.write_text("")
            with self.assertRaises(BackupError):
                client.execute("backup")
            known_hosts.write_text(saved)
        with self.subTest("wrong identity"):
            key = self.base / "wrong-key"
            subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)], check=True)
            wrong = Client(self.client_cfg | {"SSH_IDENTITY": str(key)})
            with self.assertRaises(BackupError):
                wrong.execute("backup")
        self.assertEqual(len(self.store.list_snapshots()), 1)
        self.assertTrue(self.store.verify(snapshot)["verified"])
